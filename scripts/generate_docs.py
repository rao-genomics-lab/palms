"""Generate the two reference pages that would otherwise drift: templates, API.

Both pages carry *code* — the shipped body of every analysis template, and the
signature of every function a notebook is invited to call. Copied by hand, both
go stale the first time someone edits a template or renames an argument, and a
documented call that no longer exists is worse than no documentation. So they
are derived: the template bodies come from the registry, the signatures from the
live objects, and ``tests/test_generated_docs.py`` fails if the checked-in pages
do not match what this script produces.

The prose lives *here*, in ``TEMPLATE_NOTES`` and ``API_ENTRIES``, not in the
generated markdown — regenerating must never destroy writing. Adding a template
without a note is a test failure, which is the point: the catalogue cannot
quietly fall behind the registry.

Usage::

    python scripts/generate_docs.py            # write the pages
    python scripts/generate_docs.py --check    # exit 1 if they are out of date
"""
