# ``TranscriptLoader``'s defaults resolve against the *current directory*, so a
# raw repr bakes this machine's paths into a published page. Shortening them is
# not cosmetic: an absolute path in the docs is wrong for every reader, and
# test_generated_docs.py fails if one appears.
_ABS_PATH_DEFAULT = re.compile(r"PosixPath\('([^']*)'\)")


def _shorten_paths(sig: str) -> str:
    return _ABS_PATH_DEFAULT.sub(
        lambda m: f"Path('.../{Path(m.group(1)).name}')", sig)


def _signature(module_name: str, attr: str) -> tuple[str, str]:
    """Live signature and first docstring paragraph for a documented object."""
    module = importlib.import_module(module_name)
    obj = getattr(module, attr)
    try:
        sig = _shorten_paths(str(inspect.signature(obj)))
    except (TypeError, ValueError):       # builtins and odd descriptors
        sig = "(…)"
    doc = inspect.getdoc(obj) or ""
    summary = doc.split("\n\n")[0].replace("\n", " ").strip()
    return sig, summary


def render_api_page() -> str:
    out = [BANNER, "", API_INTRO.rstrip(), ""]

    out.append("## Contents\n")
    for section in API_SECTIONS:
        out.append(f"- [{section.title}]({_anchor(section.title)})")
    viewer_heading = "Reachable, but needs a live viewer"
    out.append(f"- [{viewer_heading}]({_anchor(viewer_heading)})")
    out.append("")

    for section in API_SECTIONS:
        out.append(f"## {section.title}\n")
        out.append(section.intro + "\n")
        for entry in section.entries:
            sig, summary = _signature(entry.module, entry.name)
            out.append(f"### `{entry.name}`\n")
            out.append(f"```python\nfrom {entry.module} import {entry.name}\n"
                       f"{entry.name}{sig}\n```\n")
            out.append(entry.what + "\n")
            if summary:
                out.append(f"> {summary}\n")
            if entry.caveat:
                out.append(f"**Caveat:** {entry.caveat}\n")
            if entry.snippet:
                out.append("```python\n" + entry.snippet.strip("\n") + "\n```\n")

    out.append(VIEWER_COUPLED.rstrip())
    return "\n".join(out).rstrip() + "\n"


