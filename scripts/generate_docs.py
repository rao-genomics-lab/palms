TEMPLATES_INTRO = """\
# Analysis Templates

Every analysis the viewer runs is a **template**: a piece of plain scverse source
with a declared contract, kept in `src/xenium_viewer/utils/step_templates/builtin/`
as a `.tmpl` file. When you click a button, the owning tab builds a dictionary of
parameters, the template is rendered once, and *that same string* is both executed
and recorded in the provenance graph — so the code below is the code that runs,
and the code the exported notebook replays.

This page is the catalogue: what each template computes, its contract, and its
full default source. It is generated from the registry itself, so it cannot
disagree with what is installed.

- To **change** any of this, see the [Templates](Tab-Templates) tab — overrides
  are resolved per block, so you can edit one step without freezing the rest.
- To **see what a specific run did**, see the [Notebook](Tab-Notebook) tab; the
  provenance graph records the rendered code, not the template.
- The API behind all of it is in the [API Reference](API-Reference).

## How to read a template

A template is an ordered set of **named blocks**, delimited by `#--- block <name>`
lines. Everything structural is a comment, so the file is valid Python.

| Contract field | Meaning |
|---|---|
| `params` | The `$name` placeholders the template expects. A `?` marks an optional one. Values are substituted as Python literals. |
| `requires` | Names the template may use from the executor namespace — `sc`, `sq`, `sd`, `pd`, `np`, `plt`, `Path`, `data_path`, `sdata`, `adata`, plus anything a declared dependency binds. Referencing anything else is rejected before it can fail as a `NameError` on replay. |
| `outputs` | Results the template must bind. The executor raises if one is missing, so a template edit that stops producing a result fails immediately instead of returning stale state. |
| `assemblies` | The block combinations that are allowed to run. The **call site** decides which one to use, because the branch structure is what the widgets mean; the registry owns the text. |
| frozen blocks | Blocks that may not be customised, listed where they occur. |

Which assembly runs is decided by the tab, from your widget settings. The
[Templates](Tab-Templates) tab's preview pane shows the exact assembled and
substituted string for the settings currently in the owning tab.
"""


def _anchor(heading: str) -> str:
    """A same-page link target, by GitHub's rules.

    Lowercase, punctuation dropped, spaces to hyphens — but **underscores are
    kept**, which is the part that is easy to get wrong: `spatial_neighbors`
    anchors as `#spatial_neighbors`, not `#spatial-neighbors`.
    """
    slug = re.sub(r"[^\w\s-]", "", heading.lower())
    return "#" + re.sub(r"\s+", "-", slug.strip())


def _fence(text: str) -> str:
    """A python code fence, with the template's leading blank line trimmed."""
    return "```python\n" + text.strip("\n") + "\n```"


def _source(spec) -> str:
    """The template body, with its block markers.

    ``builtin_text`` concatenates every block, which for a multi-block template
    means mutually exclusive variants run together — `clustering.leiden` would
    read as HVG *and* scaling *and* PCA, an assembly that never runs. Showing the
    markers is how the `.tmpl` file actually looks and how the Templates tab
    shows it, so the reader can see which lines belong to which variant.
    """
    if len(spec.blocks) == 1:
        return _fence(next(iter(spec.blocks.values())).text)
    parts = []
    for name, block in spec.blocks.items():
        marker = f"#--- block {name}"
        if not block.editable:
            marker += "        # frozen: not customisable"
        parts.append(marker + "\n" + block.text.strip("\n"))
    return _fence("\n\n".join(parts))


def _params_table(spec) -> str:
    if not spec.params:
        return "_No parameters._"
    rows = ["| Parameter | Type | Required |", "|---|---|---|"]
    for p in spec.params:
        rows.append(f"| `{p.name}` | `{p.type}` | {'yes' if p.required else 'no'} |")
    return "\n".join(rows)


def _assemblies(spec) -> str:
    if len(spec.assemblies) <= 1:
        return ""
    lines = [f"- `{' + '.join(a)}`" for a in spec.assemblies]
    return "\n".join(lines)


def render_templates_page() -> str:
    # builtin_* on purpose: this page documents the *shipped* defaults, and the
    # builtin readers cannot see a user override, so it says what everyone gets
    # rather than what this machine's config resolves to. Run sites must use
    # step_template() instead — test_every_step_resolves_user_overrides checks
    # that — but a catalogue of defaults is the one place the rule inverts.
    from xenium_viewer.utils.step_templates import loader as registry

    ids = registry.builtin_ids()
    missing = sorted(set(ids) - set(TEMPLATE_NOTES))
    if missing:
        raise SystemExit(
            f"No prose for template(s) {missing} — add a TemplateNote in "
            f"{Path(__file__).name} before regenerating."
        )

    out = [BANNER, "", TEMPLATES_INTRO.rstrip(), ""]

    by_group: dict[str, list[str]] = {g: [] for g in GROUP_ORDER}
    for tid in ids:
        by_group[TEMPLATE_NOTES[tid].group].append(tid)

    out.append("## Contents\n")
    for group in GROUP_ORDER:
        for tid in by_group[group]:
            # The one-line summary is the template's own `doc:` header — written
            # for exactly this, and guaranteed to match the file. Deriving it by
            # truncating the prose at the first "." cut `adata.obs` in half.
            out.append(f"- [`{tid}`]({_anchor(tid)}) — "
                       f"{registry.builtin_spec(tid).doc}")
    out.append("")

    for group in GROUP_ORDER:
        out.append(f"## {group}\n")
        for tid in by_group[group]:
            note = TEMPLATE_NOTES[tid]
            spec = registry.builtin_spec(tid)
            out.append(f"### `{tid}`\n")
            out.append(f"**Run by:** {note.tab}\n")
            out.append(f"{note.what}\n")
            if note.reading:
                out.append(f"{note.reading}\n")
            out.append("**Contract**\n")
            out.append(_params_table(spec) + "\n")
            requires = ", ".join(f"`{n}`" for n in sorted(spec.requires)) or "_nothing_"
            outputs = ", ".join(f"`{n}`" for n in spec.outputs) or "_nothing (terminal step)_"
            out.append(f"- **Requires:** {requires}")
            out.append(f"- **Outputs:** {outputs}")
            blocks = ", ".join(f"`{n}`" for n in spec.blocks)
            out.append(f"- **Blocks:** {blocks}")
            frozen = [n for n, b in spec.blocks.items() if not b.editable]
            if frozen:
                out.append("- **Frozen (not customisable):** "
                           + ", ".join(f"`{n}`" for n in frozen))
            out.append("")
            if len(spec.assemblies) > 1:
                out.append(f"**Variants** — {len(spec.assemblies)} assemblies:\n")
                if note.variants:
                    out.append(note.variants + "\n")
                out.append(_assemblies(spec) + "\n")
            label = ("**Default source**" if len(spec.blocks) == 1
                     else "**Default source** — by block; an assembly above picks "
                          "which of these run, in that order")
            out.append(label + "\n")
            out.append(_source(spec) + "\n")

    return "\n".join(out).rstrip() + "\n"


