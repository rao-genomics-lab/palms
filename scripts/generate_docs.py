def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if a page on disk is out of date")
    args = parser.parse_args(argv)

    stale = []
    for path, render in PAGES.items():
        produced = render()
        current = path.read_text() if path.exists() else ""
        if args.check:
            if produced != current:
                stale.append(path)
                diff = difflib.unified_diff(
                    current.splitlines(), produced.splitlines(),
                    fromfile=f"{path.name} (on disk)", tofile=f"{path.name} (generated)",
                    lineterm="",
                )
                print("\n".join(list(diff)[:40]))
        else:
            path.write_text(produced)
            print(f"wrote {path.relative_to(REPO)} ({len(produced.splitlines())} lines)")

    if stale:
        print(textwrap.dedent(f"""
            {len(stale)} page(s) out of date. Regenerate with:
                python scripts/generate_docs.py
        """))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
